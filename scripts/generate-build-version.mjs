import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';

const i18nDir = resolve(process.cwd(), 'public/assets/i18n');
const outputFile = resolve(process.cwd(), 'src/environments/build-version.ts');

const files = readdirSync(i18nDir)
  .filter((file) => file.endsWith('.json'))
  .sort();

const hash = createHash('sha1');
for (const file of files) {
  hash.update(readFileSync(join(i18nDir, file)));
}

const buildVersion = hash.digest('hex').slice(0, 12);
const content =
  '// AUTO-GENERATED by scripts/generate-build-version.mjs. Do not edit.\n' +
  '// Cambia automáticamente cuando cambian los archivos de traducción.\n' +
  `export const BUILD_VERSION = '${buildVersion}';\n`;

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, content);

console.log(`BUILD_VERSION=${buildVersion} (${files.length} translation files)`);
